def get_part_name(new_ep):
    if new_ep <= 31:
        return "제1부: 각성과 다섯 소년의 맹세"
    elif new_ep <= 69:
        return "제2부: 아르카디아의 비상과 첫 네임드 아서"
    elif new_ep <= 118:
        return "제3부: 그림자 군주와 세계 암흑 제국 격파"
    elif new_ep <= 156:
        return "제4부: 대격변과 금문(Gold Gate), 완성된 이단자"
    else:
        return "제5부: 다이아몬드 게이트 최후의 결전과 영원한 봄날"

scenario_200 = []
new_ep_num = 1

for ch in orig_chapters:
    orig_ep = ch["orig_ep"]
    orig_title = ch["title"]
    orig_body = ch["body"]

    if orig_ep in SPLIT_SPECS:
        part1_spec, part2_spec = SPLIT_SPECS[orig_ep]
        paras = [p.strip() for p in orig_body.split("\n\n") if p.strip()]
        mid = max(1, len(paras) // 2)
        ref1 = "\n\n".join(paras[:mid])
        ref2 = "\n\n".join(paras[mid:]) if len(paras) > 1 else orig_body

        for idx, (sub_title, focus_desc) in enumerate([part1_spec, part2_spec], 1):
            part_name = get_part_name(new_ep_num)
            scenario_200.append({
                "ep_num": new_ep_num,
                "orig_ep": orig_ep,
                "part": part_name,
                "title": sub_title,
                "focus": focus_desc,
                "target_chars": 4500,
                "reference_text": ref1 if idx == 1 else ref2,
                "full_orig_context": orig_body
            })
            new_ep_num += 1
    else:
        part_name = get_part_name(new_ep_num)
        scenario_200.append({
            "ep_num": new_ep_num,
            "orig_ep": orig_ep,
            "part": part_name,
            "title": orig_title,
            "focus": f"원작 제{orig_ep}화 '{orig_title}'의 핵심 사건을 유지하되, 인물 간 대화·내면 심리·전투 타격감·배경 묘사를 상업 웹소설 호흡(4,000~5,000자)으로 생생하게 확장",
            "target_chars": 4500,
            "reference_text": orig_body,
            "full_orig_context": orig_body
        })
        new_ep_num += 1

